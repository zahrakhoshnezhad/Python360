x = 10 #در اینجا تطبیق میدهیم یعنی
match x :#میگیم اگر ایکس با 10 تطبیق
    case 10 :#دارد اونوقت پرینت کن 10 
        print("10")
    case 11 :
        print("11")    
    case 12 :    
        print ("12")
    case _ :    #اگر با هیچکدوم تطبیق نداشت از این استفاده میکنیم
        print("_")# _ = wildcard